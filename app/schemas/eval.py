"""Pydantic schemas for RAG Retrieval Evaluation, Search Playground, and Debugging.

Defines schemas for:
1. Evaluation Samples and Datasets (with human review tracking and origin).
2. Retrieval Playground queries and item traces with explicit score labeling.
3. Multi-method Comparison (Dense, BM25, Hybrid).
4. Strict Retrieval Metrics (Recall@K, Precision@K, MRR, nDCG@K, Hit Rate).
5. Evaluation Runs and Pipeline Version Comparisons.
6. Retrieval Debugging Traces with grounded exclusion reasons.
"""

from __future__ import annotations

from typing import Any, Literal, Optional
from pydantic import BaseModel, ConfigDict, Field


class EvalSample(BaseModel):
    """A single evaluation query sample with ground truth and provenance metadata."""

    model_config = ConfigDict(populate_by_name=True)

    sample_id: str = Field(description="Unique identifier for this sample.")
    question: str = Field(description="Query or question text.")
    job_id: str = Field(description="Associated job/dataset ID.")
    version_label: Optional[str] = Field(default=None, description="Dataset snapshot version (e.g. 'v1', 'v2').")
    expected_chunk_ids: list[str] = Field(
        default_factory=list,
        description="IDs of ground-truth relevant chunks.",
    )
    expected_source_urls: list[str] = Field(
        default_factory=list,
        description="Source URLs of expected relevant content.",
    )
    relevance_labels: dict[str, int] = Field(
        default_factory=dict,
        description="Graded relevance labels (chunk_id -> grade: 0=irrelevant, 1=relevant, 2=highly relevant).",
    )
    notes: Optional[str] = Field(default=None, description="Developer notes or edge case context.")
    origin: Literal["manual", "real", "llm_generated"] = Field(
        default="manual",
        description="Origin of the question: human-crafted (manual), real user traffic (real), or generated by LLM.",
    )
    human_reviewed: bool = Field(
        default=False,
        description="Whether this sample and its relevance labels have been verified by a human expert.",
    )
    created_at: str = Field(description="ISO timestamp of sample creation.")


class EvalDataset(BaseModel):
    """Collection of evaluation samples for benchmarking retrieval quality."""

    model_config = ConfigDict(populate_by_name=True)

    dataset_id: str = Field(description="Unique dataset identifier.")
    name: str = Field(description="Human-readable title of this evaluation set.")
    description: Optional[str] = Field(default=None, description="Detailed description of the evaluation scenario.")
    job_id: Optional[str] = Field(default=None, description="Default target job_id.")
    tenant_id: Optional[str] = Field(default=None, description="Owner tenant or workspace ID.")
    samples: list[EvalSample] = Field(default_factory=list, description="List of evaluation samples.")
    created_at: str = Field(description="ISO timestamp of dataset creation.")


class RetrievalItemTrace(BaseModel):
    """Detailed trace of a single retrieved chunk with explicit score typing."""

    model_config = ConfigDict(populate_by_name=True)

    chunk_id: str
    source_url: str
    heading_context: Optional[str] = None
    title: Optional[str] = None
    category: Optional[str] = None
    language: Optional[str] = None
    rank: int
    score: float
    raw_dense_score: Optional[float] = None
    raw_sparse_score: Optional[float] = None
    score_type: str = Field(
        description="Explicit description of the score scale (e.g. 'Cosine Similarity [0.0 - 1.0]', 'BM25 Normalized [0.0 - 1.0]', 'Hybrid Weighted Score').",
    )
    search_method: Literal["dense", "bm25", "hybrid"]
    text_preview: str
    char_count: int = 0
    neighbors_count: int = 0
    neighbors_previews: list[str] = Field(default_factory=list)


class PlaygroundSearchResult(BaseModel):
    """Response returned by the interactive retrieval playground."""

    model_config = ConfigDict(populate_by_name=True)

    query: str
    job_id: str
    tenant_id: Optional[str] = None
    version_label: Optional[str] = None
    method: Literal["dense", "bm25", "hybrid"]
    top_k: int
    alpha: float
    min_score: float
    filters_applied: dict[str, Any]
    latency_ms: float
    total_candidates_considered: int
    total_returned: int
    results: list[RetrievalItemTrace]
    score_scale_warning: str = Field(
        default="توجه: مقیاس امتیاز روش‌های مختلف با یکدیگر متفاوت است و مقایسه مستقیم عددی بین روش‌ها فاقد اعتبار است.",
    )


class MethodComparisonResult(BaseModel):
    """Side-by-side comparison of Dense, BM25, and Hybrid search for a single query."""

    model_config = ConfigDict(populate_by_name=True)

    query: str
    job_id: str
    tenant_id: Optional[str] = None
    version_label: Optional[str] = None
    top_k: int
    alpha: float
    dense_results: list[RetrievalItemTrace]
    bm25_results: list[RetrievalItemTrace]
    hybrid_results: list[RetrievalItemTrace]
    dense_supported: bool
    dense_status_message: str
    comparison_notice: str = Field(
        default="این مقایسه نتایج واقعی روی داده‌های این مجموعه را نشان می‌دهد و به معنای برتری ذاتی یا مطلق هیچ‌کدام از روش‌ها نیست.",
    )


class SampleMetrics(BaseModel):
    """Retrieval metrics calculated for an individual evaluation sample."""

    model_config = ConfigDict(populate_by_name=True)

    sample_id: str
    question: str
    has_ground_truth: bool
    recall_at_k: Optional[float] = None
    precision_at_k: Optional[float] = None
    mrr: Optional[float] = None
    ndcg_at_k: Optional[float] = None
    hit_rate: Optional[float] = None
    first_relevant_rank: Optional[int] = None
    relevant_retrieved_count: int = 0
    total_relevant_expected: int = 0
    warning: Optional[str] = None


class EvalRunConfig(BaseModel):
    """Configuration parameters preserved for a specific evaluation run."""

    model_config = ConfigDict(populate_by_name=True)

    run_id: str
    dataset_id: str
    job_id: str
    tenant_id: Optional[str] = None
    version_label: Optional[str] = None
    method: Literal["dense", "bm25", "hybrid"] = "hybrid"
    top_k: int = 5
    alpha: float = 0.7
    min_score: float = 0.0
    category_filter: Optional[str] = None
    source_url_filter: Optional[str] = None
    language_filter: Optional[str] = None
    expand_neighbors: bool = False
    created_at: str


class EvalRunResult(BaseModel):
    """Complete results and metrics summary of an evaluation run."""

    model_config = ConfigDict(populate_by_name=True)

    run_id: str
    dataset_id: str
    dataset_name: str
    tenant_id: Optional[str] = None
    config: EvalRunConfig
    total_samples: int
    samples_with_ground_truth: int
    insufficient_ground_truth: bool
    ground_truth_warning: Optional[str] = None
    aggregate_metrics: dict[str, Optional[float]] = Field(default_factory=dict)
    sample_results: list[SampleMetrics] = Field(default_factory=list)
    created_at: str


class RunComparisonResult(BaseModel):
    """Comparative analysis between two evaluation runs (e.g. pipeline versions or configs)."""

    model_config = ConfigDict(populate_by_name=True)

    run_id_a: str
    run_id_b: str
    run_a_config: EvalRunConfig
    run_b_config: EvalRunConfig
    metric_deltas: dict[str, Optional[float]] = Field(
        default_factory=dict,
        description="Metric changes: Run B value minus Run A value (positive means improvement).",
    )
    improved_queries: list[dict[str, Any]] = Field(default_factory=list)
    regressed_queries: list[dict[str, Any]] = Field(default_factory=list)
    unchanged_queries: list[dict[str, Any]] = Field(default_factory=list)
    summary_message: str


class RetrievalDebugTrace(BaseModel):
    """Diagnostic trace showing every step of candidate retrieval and filtering."""

    model_config = ConfigDict(populate_by_name=True)

    query: str
    tokens: list[str]
    detected_language: str
    method: str
    parameters: dict[str, Any]
    total_chunks_in_dataset: int
    candidates_after_metadata_filter: int
    excluded_by_metadata: int
    metadata_exclusion_sample: list[dict[str, Any]] = Field(default_factory=list)
    candidates_after_min_score: int
    excluded_by_min_score: int
    min_score_exclusion_sample: list[dict[str, Any]] = Field(default_factory=list)
    final_results_count: int
    results: list[RetrievalItemTrace] = Field(default_factory=list)
    context_expansion_status: dict[str, Any]
    actionable_warnings: list[str] = Field(default_factory=list)
